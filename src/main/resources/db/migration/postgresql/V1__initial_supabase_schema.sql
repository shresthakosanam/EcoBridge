CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_id VARCHAR(255) UNIQUE,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(20),
    address TEXT,
    location VARCHAR(255),
    profile_image_url TEXT,
    password_hash VARCHAR(100),
    role VARCHAR(30) NOT NULL DEFAULT 'ROLE_USER',
    account_status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ(6) NOT NULL,
    updated_at TIMESTAMPTZ(6) NOT NULL,
    CONSTRAINT chk_users_role CHECK (role IN ('ROLE_USER','ROLE_COLLECTOR','ROLE_ADMIN')),
    CONSTRAINT chk_users_account_status CHECK (account_status IN ('ACTIVE','SUSPENDED','DISABLED'))
);
CREATE INDEX idx_users_role_status ON users(role, account_status);

CREATE TABLE collectors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    phone VARCHAR(20) NOT NULL,
    vehicle_type VARCHAR(100),
    vehicle_number VARCHAR(50),
    service_area VARCHAR(255) NOT NULL,
    verification_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    availability_status VARCHAR(30) NOT NULL DEFAULT 'OFFLINE',
    rating NUMERIC(3,2) NOT NULL DEFAULT 0.00 CHECK (rating >= 0.00 AND rating <= 5.00),
    total_completed_pickups INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ(6) NOT NULL,
    updated_at TIMESTAMPTZ(6) NOT NULL
);
CREATE INDEX idx_collectors_service_area ON collectors(service_area);
CREATE INDEX idx_collectors_verification ON collectors(verification_status);

CREATE TABLE pickup_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_request_id VARCHAR(64) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    collector_id BIGINT REFERENCES collectors(id) ON DELETE RESTRICT,
    waste_type VARCHAR(50) NOT NULL,
    quantity_kg NUMERIC(10,2) NOT NULL CHECK (quantity_kg > 0),
    pickup_address TEXT NOT NULL,
    latitude NUMERIC(10,7),
    longitude NUMERIC(10,7),
    preferred_date DATE NOT NULL,
    preferred_time TIME(6),
    notes TEXT,
    image_url TEXT,
    status VARCHAR(40) NOT NULL DEFAULT 'REQUESTED',
    created_at TIMESTAMPTZ(6) NOT NULL,
    updated_at TIMESTAMPTZ(6) NOT NULL,
    accepted_at TIMESTAMPTZ(6),
    collected_at TIMESTAMPTZ(6),
    completed_at TIMESTAMPTZ(6),
    cancelled_at TIMESTAMPTZ(6),
    CONSTRAINT chk_pickups_status CHECK (status IN ('REQUESTED','ACCEPTED','COLLECTOR_ASSIGNED','ON_THE_WAY','COLLECTED','COMPLETED','CANCELLED','REJECTED'))
);
CREATE INDEX idx_pickups_user_created ON pickup_requests(user_id, created_at);
CREATE INDEX idx_pickups_collector_status ON pickup_requests(collector_id, status);
CREATE INDEX idx_pickups_status_date ON pickup_requests(status, preferred_date);

CREATE TABLE communities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    locality VARCHAR(255),
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ(6) NOT NULL,
    updated_at TIMESTAMPTZ(6) NOT NULL
);
CREATE INDEX idx_communities_creator ON communities(created_by);

CREATE TABLE community_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT NOT NULL REFERENCES communities(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    role VARCHAR(30) NOT NULL DEFAULT 'MEMBER',
    membership_status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    joined_at TIMESTAMPTZ(6) NOT NULL,
    CONSTRAINT uk_community_members UNIQUE (community_id, user_id)
);
CREATE INDEX idx_community_members_user ON community_members(user_id);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT REFERENCES communities(id) ON DELETE RESTRICT,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    event_date DATE NOT NULL,
    start_time TIME(6),
    end_time TIME(6),
    location VARCHAR(255) NOT NULL,
    event_type VARCHAR(80),
    capacity INTEGER CHECK (capacity IS NULL OR capacity > 0),
    image_url TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'UPCOMING',
    created_at TIMESTAMPTZ(6) NOT NULL,
    updated_at TIMESTAMPTZ(6) NOT NULL
);
CREATE INDEX idx_events_community_date ON events(community_id, event_date);
CREATE INDEX idx_events_creator ON events(created_by);
CREATE INDEX idx_events_status_date ON events(status, event_date);

CREATE TABLE event_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status VARCHAR(30) NOT NULL DEFAULT 'REGISTERED',
    registered_at TIMESTAMPTZ(6) NOT NULL,
    cancelled_at TIMESTAMPTZ(6),
    CONSTRAINT uk_event_registrations UNIQUE (event_id, user_id)
);
CREATE INDEX idx_event_registrations_user ON event_registrations(user_id);

CREATE TABLE posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    content TEXT,
    activity_type VARCHAR(80),
    image_url TEXT,
    created_at TIMESTAMPTZ(6) NOT NULL,
    updated_at TIMESTAMPTZ(6) NOT NULL
);
CREATE INDEX idx_posts_user_created ON posts(user_id, created_at);

CREATE TABLE post_likes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ(6) NOT NULL,
    CONSTRAINT uk_post_likes UNIQUE (post_id, user_id)
);
CREATE INDEX idx_post_likes_user ON post_likes(user_id);

CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ(6) NOT NULL,
    updated_at TIMESTAMPTZ(6) NOT NULL
);
CREATE INDEX idx_comments_post_created ON comments(post_id, created_at);
CREATE INDEX idx_comments_user ON comments(user_id);

CREATE TABLE stored_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    content_type VARCHAR(32) NOT NULL,
    image_data BYTEA NOT NULL,
    created_at TIMESTAMPTZ(6) NOT NULL
);
CREATE INDEX idx_stored_images_user ON stored_images(user_id);
